"""
agents/base_agent.py — Base Agent with Validated Agentic RAG
============================================================
PURPOSE:
    Defines the shared foundation for all specialized agents.
    Implements Requirement 4 (LCEL pipelines) & Requirement 5 (Agentic RAG with Validation).

AGENTIC RAG CAPABILITIES IN BASE AGENT:
    1. Targeted retrieval queries formulated by the calling agent.
    2. Quality validation: verifies chunk count and page diversity.
    3. Self-healing / Query Expansion: If initial retrieval is too narrow,
       automatically reformulates query and increases k.
    4. Quality tagging: Annotates context quality ("optimal" vs "limited") so the UI
       can inform the user if information was scarce in the paper.
"""

from abc import ABC, abstractmethod
from typing import NamedTuple
from langchain_core.documents import Document
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from core.vector_store import VectorStoreManager
from utils.llm_factory import get_llm


class ValidatedContext(NamedTuple):
    formatted_text: str
    source_pages: list[int]
    quality: str             # "optimal" | "limited" | "empty"
    retrieval_count: int


class BaseAgent(ABC):
    """Abstract base agent providing validated RAG retrieval and LCEL execution."""

    def __init__(self, vector_store: VectorStoreManager | None = None, llm=None):
        self.vector_store = vector_store or VectorStoreManager()
        self.llm = llm or get_llm()
        self.output_parser = StrOutputParser()

    def retrieve_with_validation(
        self,
        query: str,
        collection_id: str,
        k: int = 6,
        min_pages: int = 2,
    ) -> ValidatedContext:
        """
        Executes agentic retrieval with context quality validation and adaptive query expansion.
        
        Args:
            query: Domain-specific query generated by the agent.
            collection_id: Unique identifier for the paper in ChromaDB.
            k: Initial number of chunks to retrieve.
            min_pages: Minimum number of unique pages expected for broad coverage.
            
        Returns:
            ValidatedContext: Clean formatted context, list of source pages, and quality flag.
        """
        # Step 1: Initial retrieval
        chunks = self.vector_store.retrieve_chunks(query, collection_id=collection_id, k=k)

        if not chunks:
            return ValidatedContext(
                formatted_text="No relevant information found in the uploaded research paper.",
                source_pages=[],
                quality="empty",
                retrieval_count=0,
            )

        unique_pages = sorted(list(set(c.metadata.get("page", 0) for c in chunks if "page" in c.metadata)))

        # Step 2: Validation check — if page spread is too narrow, trigger query expansion
        if len(unique_pages) < min_pages and len(chunks) < 10:
            expanded_query = f"{query} introduction methodology results discussion conclusion"
            additional_chunks = self.vector_store.retrieve_chunks(
                expanded_query, collection_id=collection_id, k=k + 4
            )
            # Deduplicate chunks based on text content
            existing_texts = {c.page_content for c in chunks}
            for c in additional_chunks:
                if c.page_content not in existing_texts:
                    chunks.append(c)
                    existing_texts.add(c.page_content)

            unique_pages = sorted(list(set(c.metadata.get("page", 0) for c in chunks if "page" in c.metadata)))

        # Step 3: Determine quality flag
        quality = "optimal" if len(unique_pages) >= min_pages and len(chunks) >= 3 else "limited"

        # Step 4: Format context string with page citations
        formatted_blocks = []
        for c in chunks:
            page_num = c.metadata.get("page", "?")
            formatted_blocks.append(f"[Source Page {page_num}]:\n{c.page_content}")

        formatted_text = "\n\n---\n\n".join(formatted_blocks)

        return ValidatedContext(
            formatted_text=formatted_text,
            source_pages=unique_pages,
            quality=quality,
            retrieval_count=len(chunks),
        )

    def _build_lcel_chain(self, prompt: ChatPromptTemplate):
        """
        Constructs a genuine LCEL chain using the pipe operator (|).
        Pipeline: prompt | llm | output_parser
        """
        return prompt | self.llm | self.output_parser

    @abstractmethod
    def run(self, collection_id: str, **kwargs) -> dict:
        """Each agent must implement its primary execution method."""
        pass
