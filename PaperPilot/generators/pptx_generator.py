"""
generators/pptx_generator.py — PowerPoint Presentation Builder
=============================================================
PURPOSE:
    Transforms structured slide data into a downloadable, beautifully formatted
    PowerPoint presentation (.pptx) using python-pptx.
    Implements Requirement 2 (PowerPoint Presentation Generation) and Requirement 5.

DESIGN HIGHLIGHTS:
    - 16:9 widescreen format (13.33 x 7.5 inches)
    - Professional academic color palette (Navy Blue, Slate Grey, Crisp White)
    - Clean typography with title banners and structured bullet points
"""

from pathlib import Path
import re
from datetime import datetime
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from pptx.enum.shapes import MSO_SHAPE
from config import settings


# ── Presentation Theme Colors ─────────────────────────────────────────────────
NAVY_PRIMARY = RGBColor(26, 54, 93)      # #1A365D - Deep academic navy
ACCENT_BLUE  = RGBColor(49, 130, 206)    # #3182CE - Vibrant accent
DARK_TEXT    = RGBColor(45, 55, 72)      # #2D3748 - Charcoal text
LIGHT_BG     = RGBColor(247, 250, 252)   # #F7FAFC - Off-white canvas
WHITE        = RGBColor(255, 255, 255)


def sanitize_filename(name: str) -> str:
    """Creates a filesystem-safe filename."""
    clean = re.sub(r'[^a-zA-Z0-9_\-\.]', '_', name)
    return clean[:50]


def create_presentation_from_slides(
    slides: list[dict],
    presentation_title: str = "Research Paper Presentation",
    output_filename: str | None = None,
) -> Path:
    """
    Creates and saves a .pptx file based on structured slide dictionaries.
    
    Args:
        slides: List of slide dicts, each with keys 'title' and 'bullets'.
        presentation_title: Main title of the research paper presentation.
        output_filename: Optional custom output file name.
        
    Returns:
        Path: Absolute path to the saved .pptx presentation file.
    """
    prs = Presentation()

    # Configure 16:9 Widescreen Layout (13.33 inches x 7.5 inches)
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    blank_layout = prs.slide_layouts[6]  # Blank slide for full design control

    # ── SLIDE 1: Professional Title Slide ─────────────────────────────────────
    title_slide = prs.slides.add_slide(blank_layout)

    # Background banner
    banner = title_slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE,
        Inches(0), Inches(0), Inches(13.333), Inches(4.5)
    )
    banner.fill.solid()
    banner.fill.fore_color.rgb = NAVY_PRIMARY
    banner.line.color.rgb = NAVY_PRIMARY

    # Title text box inside banner
    title_box = title_slide.shapes.add_textbox(
        Inches(1.0), Inches(1.2), Inches(11.333), Inches(2.2)
    )
    tf = title_box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = presentation_title
    p.font.name = "Arial"
    p.font.size = Pt(36)
    p.font.bold = True
    p.font.color.rgb = WHITE
    p.alignment = PP_ALIGN.LEFT

    # Subtitle box in lower portion
    sub_box = title_slide.shapes.add_textbox(
        Inches(1.0), Inches(4.8), Inches(11.333), Inches(2.0)
    )
    sub_tf = sub_box.text_frame
    sub_tf.word_wrap = True
    p_sub = sub_tf.paragraphs[0]
    p_sub.text = "Academic Paper Analysis & Presentation"
    p_sub.font.name = "Calibri"
    p_sub.font.size = Pt(20)
    p_sub.font.bold = True
    p_sub.font.color.rgb = NAVY_PRIMARY

    p_meta = sub_tf.add_paragraph()
    p_meta.text = f"Generated by PaperPilot AI  •  {datetime.now().strftime('%B %Y')}"
    p_meta.font.name = "Calibri"
    p_meta.font.size = Pt(14)
    p_meta.font.color.rgb = DARK_TEXT

    # ── SLIDES 2+: Content Slides ─────────────────────────────────────────────
    # If first slide in 'slides' is already a title, skip it to avoid duplication
    content_slides = slides[1:] if len(slides) > 1 and "title" in slides[0].get("title", "").lower() else slides

    for idx, slide_info in enumerate(content_slides, 2):
        slide = prs.slides.add_slide(blank_layout)
        title_text = slide_info.get("title", f"Slide {idx}")
        bullets = slide_info.get("bullets", [])

        # Top Header Accent Bar
        header_bar = slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE,
            Inches(0.8), Inches(0.5), Inches(0.15), Inches(0.8)
        )
        header_bar.fill.solid()
        header_bar.fill.fore_color.rgb = ACCENT_BLUE
        header_bar.line.color.rgb = ACCENT_BLUE

        # Slide Title
        t_box = slide.shapes.add_textbox(Inches(1.1), Inches(0.4), Inches(11.4), Inches(1.0))
        t_tf = t_box.text_frame
        t_tf.word_wrap = True
        p_title = t_tf.paragraphs[0]
        p_title.text = title_text
        p_title.font.name = "Arial"
        p_title.font.size = Pt(26)
        p_title.font.bold = True
        p_title.font.color.rgb = NAVY_PRIMARY

        # Slide Number in top right
        num_box = slide.shapes.add_textbox(Inches(11.8), Inches(0.4), Inches(1.0), Inches(0.6))
        p_num = num_box.text_frame.paragraphs[0]
        p_num.text = f"{idx:02d}"
        p_num.font.name = "Arial"
        p_num.font.size = Pt(14)
        p_num.font.color.rgb = ACCENT_BLUE
        p_num.alignment = PP_ALIGN.RIGHT

        # Content Box for bullet points
        c_box = slide.shapes.add_textbox(Inches(1.1), Inches(1.8), Inches(11.0), Inches(5.0))
        c_tf = c_box.text_frame
        c_tf.word_wrap = True

        for b_idx, bullet in enumerate(bullets):
            p_bullet = c_tf.paragraphs[0] if b_idx == 0 else c_tf.add_paragraph()
            p_bullet.text = bullet
            p_bullet.font.name = "Calibri"
            p_bullet.font.size = Pt(18)
            p_bullet.font.color.rgb = DARK_TEXT
            p_bullet.level = 0
            p_bullet.space_after = Pt(14)

    # ── Save Presentation to outputs/ ─────────────────────────────────────────
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    clean_title = sanitize_filename(presentation_title)
    filename = output_filename or f"{clean_title}_{timestamp}.pptx"
    out_path = settings.OUTPUT_DIR / filename

    prs.save(str(out_path))
    return out_path
